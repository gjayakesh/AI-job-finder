#!/usr/bin/env bash
# Builds index.html (the website) and worker/engine.mjs (shared scoring engine for the server job) from src/.
set -euo pipefail
cd "$(dirname "$0")/.."
cat src/00-utils.js src/01-core.js src/02-engine.js src/03-views.js src/04-actions.js src/05-site.js src/06-boot.js > /tmp/aca-app.js
node --check /tmp/aca-app.js
{ cat src/head.html; echo '<script src="config.js"></script>'; echo '<script>'; cat /tmp/aca-app.js; echo '</script>'; echo '</body>'; echo '</html>'; } > index.html
{ echo '// GENERATED by tools/build.sh from src/00-utils.js + src/02-engine.js. Do not edit by hand.';
  cat src/00-utils.js src/02-engine.js
  echo 'export { uid, nowISO, clone, esc, uniqCI, splitList, clamp, sum, pct, lpa, lpaNum, salaryRange, fmtDate, stableStringify, DEFAULT_WEIGHTS, SOURCE_NAME, STAGES, reached, detectSkills, canonSkill, detectCities, detectWorkMode, detectEmployment, parseSalary, parseExperience, extractJobLocal, scamCheck, scoreJob, category, normalizeUrl, externalId, fingerprint, findDuplicate, analytics, buildReport, candidateYears, isoDay };'
} > worker/engine.mjs
node --check worker/engine.mjs
echo "built index.html ($(wc -c < index.html) bytes) and worker/engine.mjs"
